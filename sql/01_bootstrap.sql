-- Create our project warehouse using the required role.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS TA_DATA_PROJECT_WH
    WAREHOUSE_SIZE='XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS TA_DATA_DB;
CREATE SCHEMA IF NOT EXISTS TA_DATA_DB.RAW;
CREATE SCHEMA IF NOT EXISTS TA_DATA_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS TA_DATA_DB.MARTS;   

USE WAREHOUSE TA_DATA_PROJECT_WH;
USE DATABASE TA_DATA_DB;
USE SCHEMA RAW;

USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS TA_DATA_ENGINEER;

SET project_user = CURRENT_USER();
GRANT ROLE TA_DATA_ENGINEER TO USER IDENTIFIER($project_user);

SHOW GRANTS ON WAREHOUSE TA_DATA_PROJECT_WH;

GRANT USAGE ON WAREHOUSE TA_DATA_PROJECT_WH TO TA_DATA_ENGINEER;
GRANT USAGE ON DATABASE TA_DATA_DB TO TA_DATA_ENGINEER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE TA_DATA_DB TO TA_DATA_ENGINEER;
GRANT ALL ON DATABASE TA_DATA_DB TO TA_DATA_ENGINEER;

USE ROLE TA_DATA_ENGINEER;