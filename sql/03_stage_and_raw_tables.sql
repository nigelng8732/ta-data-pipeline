-- Grant project role permission to the S3 integration as well as to create objects.
USE ROLE ACCOUNTADMIN;

GRANT USAGE ON INTEGRATION TA_S3_INTEGRATION TO ROLE TA_DATA_ENGINEER;

GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT
    ON SCHEMA TA_DATA_DB.RAW
    TO ROLE TA_DATA_ENGINEER;

-- Assume project role and configuration.
USE ROLE TA_DATA_ENGINEER;
USE WAREHOUSE TA_DATA_PROJECT_WH;
USE DATABASE TA_DATA_DB;
USE SCHEMA RAW;

-- Define how Snowflake should interpret our files.
CREATE FILE FORMAT IF NOT EXISTS TA_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('')
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    ENCODING = 'UTF8';

-- Create stage for the S3 integration.
CREATE STAGE TA_S3_STAGE
    STORAGE_INTEGRATION = TA_S3_INTEGRATION
    URL = 's3://ta-data-pipeline-project/ta/snapshots/'
    FILE_FORMAT = (
        FORMAT_NAME = 'TA_DATA_DB.RAW.TA_CSV_FORMAT'
    );

-- Create the new RAW tables.
CREATE TABLE IF NOT EXISTS JOB_REQUISITIONS (
    JOB_REQ_ID          VARCHAR,
    JOB_TITLE           VARCHAR,
    JOB_GRADE           VARCHAR,
    BUSINESS_AREA       VARCHAR,
    COUNTRY             VARCHAR,
    RECRUITER_ID        VARCHAR,
    REQUISITION_STATUS  VARCHAR,
    APPROVED_DATE       VARCHAR,
    CLOSED_DATE         VARCHAR,
    SNAPSHOT_DATE       VARCHAR,

    SOURCE_FILENAME     VARCHAR,
    SOURCE_ROW_NUMBER   NUMBER,
    SOURCE_CONTENT_KEY  VARCHAR,
    INGESTED_AT         TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS APPLICATIONS (
    APPLICATION_ID      VARCHAR,
    JOB_REQ_ID          VARCHAR,
    CANDIDATE_ID        VARCHAR,
    CANDIDATE_NAME      VARCHAR,
    APPLICATION_STATUS  VARCHAR,
    CANDIDATE_COUNTRY   VARCHAR,
    APPLICATION_DATE    VARCHAR,
    SNAPSHOT_DATE       VARCHAR,

    SOURCE_FILENAME     VARCHAR,
    SOURCE_ROW_NUMBER   NUMBER,
    SOURCE_CONTENT_KEY  VARCHAR,
    INGESTED_AT         TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS RECRUITERS (
    RECRUITER_ID         VARCHAR,
    RECRUITER_NAME       VARCHAR,
    RECRUITER_ORG_UNIT   VARCHAR,
    SNAPSHOT_DATE       VARCHAR,

    SOURCE_FILENAME     VARCHAR,
    SOURCE_ROW_NUMBER   NUMBER,
    SOURCE_CONTENT_KEY  VARCHAR,
    INGESTED_AT         TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS APPLICATION_STATUS_AUDIT (
    APPLICATION_ID      VARCHAR,
    APPLICATION_STATUS  VARCHAR,
    CREATED_DATE        VARCHAR,
    SNAPSHOT_DATE       VARCHAR,

    SOURCE_FILENAME     VARCHAR,
    SOURCE_ROW_NUMBER   NUMBER,
    SOURCE_CONTENT_KEY  VARCHAR,
    INGESTED_AT         TIMESTAMP_LTZ
);

-- Verify the newly created objects.
SHOW FILE FORMATS IN SCHEMA TA_DATA_DB.RAW;
SHOW STAGES IN SCHEMA TA_DATA_DB.RAW;
SHOW TABLES IN SCHEMA TA_DATA_DB.RAW;

LIST @TA_DATA_DB.RAW.TA_S3_STAGE/2026-10-08/;