USE ROLE TA_DATA_ENGINEER;
USE WAREHOUSE TA_DATA_PROJECT_WH;
USE DATABASE TA_DATA_DB;
USE SCHEMA RAW;

-- Load only the first SNAPSHOT
COPY INTO JOB_REQUISITIONS (
    JOB_REQ_ID,
    JOB_TITLE,
    JOB_GRADE,
    BUSINESS_AREA,
    COUNTRY,
    RECRUITER_ID,
    REQUISITION_STATUS,
    APPROVED_DATE,
    CLOSED_DATE,
    SNAPSHOT_DATE,
    SOURCE_FILENAME,
    SOURCE_ROW_NUMBER,
    SOURCE_CONTENT_KEY,
    INGESTED_AT
)
FROM (
    SELECT
        s.$1, s.$2, s.$3, s.$4, s.$5,
        s.$6, s.$7, s.$8, s.$9, s.$10,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        METADATA$FILE_CONTENT_KEY,
        METADATA$START_SCAN_TIME
    FROM @TA_S3_STAGE/2026-10-09/ s
)
FILES = ('job_requisitions.csv')
ON_ERROR = 'ABORT_STATEMENT'
FORCE = FALSE;


COPY INTO APPLICATIONS (
    APPLICATION_ID,
    JOB_REQ_ID,
    CANDIDATE_ID,
    CANDIDATE_NAME,
    APPLICATION_STATUS,
    CANDIDATE_COUNTRY,
    APPLICATION_DATE,
    SNAPSHOT_DATE,
    SOURCE_FILENAME,
    SOURCE_ROW_NUMBER,
    SOURCE_CONTENT_KEY,
    INGESTED_AT
)
FROM (
    SELECT
        s.$1, s.$2, s.$3, s.$4, 
        s.$5, s.$6, s.$7, s.$8,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        METADATA$FILE_CONTENT_KEY,
        METADATA$START_SCAN_TIME
    FROM @TA_S3_STAGE/2026-10-09/ s 
)
FILES = ('applications.csv')
ON_ERROR = 'ABORT_STATEMENT'
FORCE = FALSE;


COPY INTO RECRUITERS (
